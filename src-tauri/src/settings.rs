// Preferences, stored as plain JSON in %APPDATA%\Tute\settings.json.

use serde::{Deserialize, Serialize};
use std::path::PathBuf;

/// Folder name under %APPDATA% and %LOCALAPPDATA%.
const APP_DIR: &str = "Tute";

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct Settings {
    pub sound_enabled: bool,
    pub sound_volume: f64,
    pub auto_close_interval: f64,
    pub absence_interval: f64,
    /// "primary" = the main display, "cursor" = whichever display the mouse is on,
    /// "monitor:<device name>" = one specific display (falls back to the main one
    /// while it is unplugged).
    pub screen: String,
    pub autostart: bool,
    /// False: the small bar always stays at the top. True: it hides when idle.
    pub hide_when_idle: bool,
    /// "tute" or "tutee"; None until the user picks on first launch.
    pub personality: Option<String>,
    /// AI providers the user added. Their keys are in the Credential Manager
    /// (see secrets.rs), never here.
    pub providers: Vec<Provider>,
    /// The model the island uses, if one is chosen.
    pub active_model: Option<ActiveModel>,
    /// The Linear team new issues go to: the last one picked on the island.
    pub linear_team: Option<String>,
    /// How the island chat talks: "fun" (playful) or "focus" (short and plain).
    pub chat_mode: String,
    /// "Do it with Claude": the folder Claude works in, per Linear team.
    pub claude_folders: std::collections::HashMap<String, String>,
    /// When Claude finishes an issue: post its summary, move it to review.
    pub claude_done_comment: bool,
    pub claude_done_review: bool,
    /// The bond with the character: points, level, what it wears. Owned by the
    /// island (src/island/bond.ts); kept here as-is so it survives restarts.
    pub bond: Option<serde_json::Value>,
}

/// Which wire protocol a provider speaks.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum ProviderKind {
    /// OpenAI Chat Completions — OpenAI itself, GLM (Z.ai / BigModel), DeepSeek,
    /// OpenRouter, Groq, Ollama, LM Studio and most others.
    OpenAi,
    /// Anthropic's own Messages API (Claude).
    Anthropic,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Provider {
    /// Generated by the settings page; also names the key in the Credential Manager.
    pub id: String,
    pub name: String,
    pub kind: ProviderKind,
    /// API root, e.g. `https://api.openai.com/v1` or `https://api.anthropic.com`.
    pub base_url: String,
    /// Model ids the user added for this provider.
    #[serde(default)]
    pub models: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ActiveModel {
    pub provider_id: String,
    pub model: String,
}

impl Default for Settings {
    fn default() -> Self {
        Self {
            sound_enabled: true,
            sound_volume: 0.12,
            auto_close_interval: 15.0,
            absence_interval: 180.0,
            screen: "primary".into(),
            autostart: false,
            hide_when_idle: false,
            personality: None,
            providers: Vec::new(),
            active_model: None,
            linear_team: None,
            chat_mode: "fun".into(),
            claude_folders: Default::default(),
            claude_done_comment: true,
            claude_done_review: true,
            bond: None,
        }
    }
}

/// %APPDATA%\Tute
pub fn config_dir() -> PathBuf {
    let base = std::env::var_os("APPDATA")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("."));
    base.join(APP_DIR)
}

/// %LOCALAPPDATA%\Tute — the log and the dropped-file inbox.
pub fn local_dir() -> PathBuf {
    let base = std::env::var_os("LOCALAPPDATA")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("."));
    base.join(APP_DIR)
}

fn settings_path() -> PathBuf {
    config_dir().join("settings.json")
}

pub fn load() -> Settings {
    match std::fs::read(settings_path()) {
        Ok(bytes) => serde_json::from_slice(&bytes).unwrap_or_default(),
        Err(_) => Settings::default(),
    }
}

pub fn save(settings: &Settings) -> std::io::Result<()> {
    let dir = config_dir();
    std::fs::create_dir_all(&dir)?;
    let json = serde_json::to_vec_pretty(settings)
        .map_err(|e| std::io::Error::new(std::io::ErrorKind::InvalidData, e))?;
    std::fs::write(settings_path(), json)
}
